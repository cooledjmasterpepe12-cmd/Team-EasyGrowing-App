const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem('eg_lang') || 'de');
  const setLang = (l) => { localStorage.setItem('eg_lang', l); localStorage.setItem('lang', l); setLangState(l); };
  const t = useCallback((key) => (DICT[lang]?.[key] || DICT.en?.[key] || key), [lang]);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
